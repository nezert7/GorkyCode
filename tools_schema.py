from datetime import datetime, timedelta
from typing import Optional, List, Dict, Any

DAYS_RU = [
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье"
]


def build_calendar_cheat_sheet(now: datetime) -> str:
    lines = []
    for offset in range(1, 15):
        dt = now + timedelta(days=offset)
        day_name = DAYS_RU[dt.weekday()]
        label = ""
        if offset == 1:
            label = " (ЗАВТРА)"
        elif offset == 2:
            label = " (ПОСЛЕЗАВТРА)"
        elif offset == 7:
            label = " (ЧЕРЕЗ НЕДЕЛЮ)"
        lines.append(f"- {day_name}{label}: {dt.strftime('%Y-%m-%d')}")
    return "\n".join(lines)


def build_system_prompt(now: datetime, active_items: Optional[List[Dict[str, Any]]] = None) -> str:
    today_str = now.strftime("%Y-%m-%d")
    weekday_str = DAYS_RU[now.weekday()]
    now_time_str = now.strftime("%H:%M")
    tomorrow_str = (now + timedelta(days=1)).strftime("%Y-%m-%d")
    yesterday_str = (now - timedelta(days=1)).strftime("%Y-%m-%d")
    calendar_sheet = build_calendar_cheat_sheet(now)

    days_until_sunday = 6 - now.weekday()
    end_of_week_str = (now + timedelta(days=days_until_sunday)).strftime("%Y-%m-%d")

    active_context = ""
    if active_items:
        lines = []
        for it in active_items[:15]:
            lines.append(
                f"  * ID={it.get('id')} [{it.get('intent')}] «{it.get('action')}» "
                f"(дата: {it.get('parsed_date')}, время: {it.get('parsed_time')})"
            )
        active_context = "\nТекущие активные записи пользователя (для команд переноса/удаления/выполнения):\n" + "\n".join(lines) + "\n"

